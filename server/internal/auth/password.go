package auth

import (
	"crypto/rand"
	"crypto/subtle"
	"encoding/hex"
	"errors"
	"fmt"
	"strconv"
	"strings"
	"unicode/utf8"

	"golang.org/x/crypto/scrypt"
)

const (
	ScryptN        = 32768
	ScryptR        = 8
	ScryptP        = 1
	ScryptKeyLen   = 32
	SaltBytes      = 16
	MinPasswordLen = 8
)

// HashPassword derives a salted scrypt hash suitable for storage.
func HashPassword(plain string) (string, error) {
	if utf8.RuneCountInString(plain) < MinPasswordLen {
		return "", fmt.Errorf("password must be at least %d characters", MinPasswordLen)
	}

	var salt [SaltBytes]byte
	if _, err := rand.Read(salt[:]); err != nil {
		return "", fmt.Errorf("generate password salt: %w", err)
	}
	key, err := scrypt.Key([]byte(plain), salt[:], ScryptN, ScryptR, ScryptP, ScryptKeyLen)
	if err != nil {
		return "", fmt.Errorf("derive password hash: %w", err)
	}
	return fmt.Sprintf("scrypt$%d$%d$%d$%x$%x", ScryptN, ScryptR, ScryptP, salt, key), nil
}

// VerifyPassword compares a password with a stored scrypt hash in constant time.
func VerifyPassword(plain, encoded string) (bool, error) {
	parts := strings.SplitN(encoded, "$", 7)
	if len(parts) != 6 || parts[0] != "scrypt" {
		return false, errors.New("invalid password hash format")
	}

	n, nErr := strconv.Atoi(parts[1])
	r, rErr := strconv.Atoi(parts[2])
	p, pErr := strconv.Atoi(parts[3])
	// Cap verification at the resource cost of hashes generated by HashPassword.
	if nErr != nil || rErr != nil || pErr != nil ||
		n < 2 || n > ScryptN || n&(n-1) != 0 || r < 1 || r > ScryptR || p < 1 || p > ScryptP {
		return false, errors.New("invalid scrypt parameters")
	}
	if len(parts[4]) != hex.EncodedLen(SaltBytes) || len(parts[5]) != hex.EncodedLen(ScryptKeyLen) {
		return false, errors.New("invalid password salt or hash length")
	}

	salt, err := hex.DecodeString(parts[4])
	if err != nil {
		return false, errors.New("invalid password salt encoding")
	}
	want, err := hex.DecodeString(parts[5])
	if err != nil {
		return false, errors.New("invalid password hash encoding")
	}
	got, err := scrypt.Key([]byte(plain), salt, n, r, p, ScryptKeyLen)
	if err != nil {
		return false, fmt.Errorf("derive password hash: %w", err)
	}
	return subtle.ConstantTimeCompare(got, want) == 1, nil
}
